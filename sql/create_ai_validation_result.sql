-- Shared AI validation result table for CORRECTIVE, NCM, and other modules.
-- This script only creates schema objects. It does not modify application behavior.

CREATE TABLE IF NOT EXISTS AI_VALIDATION_RESULT (
  VALIDATION_ID BIGINT NOT NULL AUTO_INCREMENT,
  MODULE_TYPE VARCHAR(40) NOT NULL,
  RECORD_ID VARCHAR(40) NOT NULL,
  SECTION_TYPE VARCHAR(60) NOT NULL,

  SCORE INT NULL,
  IS_VALID TINYINT(1) NULL,
  ISSUES_JSON LONGTEXT NULL,
  SUMMARY TEXT NULL,
  RECOMMENDED_FIX TEXT NULL,

  PROMPT_NAME VARCHAR(100) NULL,
  PROMPT_VERSION VARCHAR(30) NULL,
  MODEL_ID VARCHAR(100) NULL,

  INPUT_HASH CHAR(64) NULL,
  RAW_RESPONSE_JSON LONGTEXT NULL,

  VALIDATION_STATUS VARCHAR(20) NOT NULL DEFAULT 'SUCCESS',
  ERROR_MESSAGE TEXT NULL,

  VALIDATED_BY VARCHAR(30) NULL,
  VALIDATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

  PRIMARY KEY (VALIDATION_ID),
  UNIQUE KEY UQ_AI_VALIDATION_CURRENT (MODULE_TYPE, RECORD_ID, SECTION_TYPE),
  KEY IX_AI_VALIDATION_MODULE_RECORD (MODULE_TYPE, RECORD_ID),
  KEY IX_AI_VALIDATION_SECTION (SECTION_TYPE),
  KEY IX_AI_VALIDATION_VALIDATED_AT (VALIDATED_AT),
  KEY IX_AI_VALIDATION_STATUS (VALIDATION_STATUS)
);


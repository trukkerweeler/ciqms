CREATE TABLE IF NOT EXISTS AI_VALIDATION_RESULT_HISTORY (
  VALIDATION_HISTORY_ID BIGINT NOT NULL AUTO_INCREMENT,
  MODULE_TYPE VARCHAR(40) NOT NULL,
  RECORD_ID VARCHAR(80) NOT NULL,
  SECTION_TYPE VARCHAR(60) NOT NULL,
  SCORE TINYINT NULL,
  IS_VALID TINYINT(1) NULL,
  ISSUES_JSON JSON NULL,
  SUMMARY VARCHAR(512) NULL,
  RECOMMENDED_FIX TEXT NULL,
  PROMPT_NAME VARCHAR(120) NULL,
  PROMPT_VERSION VARCHAR(32) NULL,
  MODEL_ID VARCHAR(120) NULL,
  VALIDATION_STATUS VARCHAR(20) NULL,
  ERROR_MESSAGE VARCHAR(512) NULL,
  VALIDATED_BY VARCHAR(60) NULL,
  VALIDATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (VALIDATION_HISTORY_ID),
  KEY idx_avrh_record (MODULE_TYPE, RECORD_ID, SECTION_TYPE, VALIDATED_AT),
  KEY idx_avrh_status (VALIDATION_STATUS, VALIDATED_AT)
);
